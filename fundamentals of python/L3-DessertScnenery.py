import turtle
t = turtle.Turtle()
t.speed(10)

#background
sc = turtle.Screen()
sc.setup(1000,1000)
sc.bgcolor('sky blue')

#blazing sun
t.pencolor('sky blue')
t.fillcolor('yellow')
t.penup()
t.goto(250,250)
t.pendown()
t.begin_fill()
for i in range(4):
  t.forward(80)
  t.right(90)
t.end_fill()
t.penup()
t.goto(290,270)
t.pendown()
t.right(45)
t.begin_fill()
for i in range(4):
  t.forward(80)
  t.right(90)
t.end_fill()


#pyramid
t.pencolor('orange')
t.fillcolor('goldenrod')
t.penup()
t.goto(-100,-100)
t.pendown()
t.left(45)
t.begin_fill()
for i in range(3):
  t.forward(240)
  t.left(120)
t.end_fill()

#sand
t.pencolor('black')
t.fillcolor('orange')
t.penup()
t.goto(-100,-100)
t.backward(500)
t.pendown()
t.begin_fill()
t.forward(1300)
t.right(90)
t.forward(80)
t.right(90)
t.forward(1300)
t.right(90)
t.forward(80)
t.end_fill()

#striped lines
t.pencolor('orange')
t.pensize(5)
t.right(90)
def go_to(x,y):
  t.penup()
  t.goto(x,y)
  t.pendown()
go_to(-10,60)
t.forward(60)
go_to(-40,10)
t.forward(120)
go_to(-70,-40)
t.forward(180)
go_to(-100,-100)
t.forward(240)

#hump like structure
t.pencolor('black')
t.fillcolor('goldenrod')
t.pensize(1)
t.penup()
t.goto(250,-100)
t.pendown()
t.left(90)
t.begin_fill()
for i in range(19):
  t.forward(15)
  t.right(10)
t.end_fill()

#cactus
t.penup()
t.goto(350,-10)
t.pendown()
t.right(95)
t.begin_fill()
t.pencolor("black")
t.fillcolor("green")
t.right(75)
t.forward(35)
t.right(90)
t.circle(20, 90)
t.forward(10)
t.circle(20, 90)
t.left(90)
t.forward(20)
t.left(180)
t.forward(20)
t.circle(20, 180)
t.forward(20)
t.right(180)
t.forward(20)
t.left(90)
t.circle(20, 180)
t.right(90)
t.forward(50)
t.left(90)
t.forward(40)
t.left(90)
t.forward(10)
t.end_fill()

sc.mainloop()